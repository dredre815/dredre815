    raw=base64.b85decode(PAYLOAD.encode())
    actual=hashlib.sha256(raw).hexdigest()
    if actual != ARCHIVE_SHA256: raise RuntimeError(f"archive hash mismatch: {actual}")
    a.out.mkdir(parents=True, exist_ok=True)
    data=lzma.decompress(raw)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:") as tf:
        for member in tf.getmembers():
            target=(a.out/member.name).resolve()
            if a.out.resolve() not in target.parents and target != a.out.resolve():
                raise RuntimeError(f"unsafe archive member: {member.name}")
        tf.extractall(a.out, filter="data")
    print(f"materialized follow-up harness at {a.out}; sha256={actual}")
